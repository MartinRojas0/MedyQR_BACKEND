DO $migration$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.qr_emergencia
        WHERE paciente_id IS NULL
           OR NOT EXISTS (
                SELECT 1 FROM public.pacientes p
                WHERE p.id = qr_emergencia.paciente_id
           )
    ) THEN
        RAISE EXCEPTION 'Resolve QR rows without a valid patient before applying the migration';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'qr_emergencia'
          AND column_name = 'token'
          AND data_type <> 'uuid'
    ) THEN
        RAISE EXCEPTION 'qr_emergencia.token must be UUID; review the existing table before migration';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.qr_emergencia
        WHERE token_hash IS NOT NULL
          AND token_hash !~ '^[0-9a-f]{64}$'
    ) THEN
        RAISE EXCEPTION 'Existing QR token hashes must be reviewed before migration';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.qr_emergencia
        WHERE token_hash IS NOT NULL
        GROUP BY token_hash
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION 'Duplicate QR token hashes must be resolved before migration';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.qr_emergencia
        WHERE activo = TRUE AND token_hash IS NOT NULL
        GROUP BY paciente_id
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION 'Resolve multiple active secure QR tokens per patient before migration';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'qr_emergencia'
          AND column_name = 'id'
          AND data_type = 'bigint'
    ) THEN
        RAISE EXCEPTION 'qr_emergencia.id must be BIGINT; review the existing table before migration';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'qr_emergencia'
          AND column_name = 'paciente_id'
          AND data_type = 'bigint'
    ) THEN
        RAISE EXCEPTION 'qr_emergencia.paciente_id must be BIGINT; review the existing table before migration';
    END IF;
END
