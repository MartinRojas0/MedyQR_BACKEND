CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(255) NOT NULL DEFAULT 'PACIENTE',
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES public.usuarios(id),
    nombres VARCHAR(255) NOT NULL DEFAULT '',
    apellidos VARCHAR(255) NOT NULL DEFAULT '',
    documento_identidad VARCHAR(255),
    fecha_nacimiento DATE,
    telefono VARCHAR(255),
    direccion VARCHAR(255),
    sexo VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.historial_clinico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL UNIQUE REFERENCES public.pacientes(id),
    tipo_sangre VARCHAR(255),
    alergias VARCHAR(255),
    enfermedades_cronicas VARCHAR(255),
    cirugias VARCHAR(255),
    observaciones VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.registro_accesos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT REFERENCES public.pacientes(id),
    personal_id BIGINT,
    tipo_acceso VARCHAR(255),
    accion VARCHAR(255),
    fecha_acceso TIMESTAMPTZ,
    identificador_qr UUID
);
